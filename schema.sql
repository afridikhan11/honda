-- ---- Parts Sale: bump inv, insert sale + items, decrement stock ----
create or replace function fn_hw_sale(p_sid bigint, p jsonb)
returns jsonb language plpgsql as $fn$
declare v_no int; v_inv text; v_id bigint; it jsonb; yr text := to_char(now(),'YYYY');
begin
  update hw_shops set inv_no = inv_no + 1 where id = p_sid returning inv_no into v_no;
  v_inv := 'INV-'||yr||'-'||v_no;
  insert into hw_sales(shop_id,inv,customer,phone,salesman,date,subtotal,discount,total,pay,ts)
    values (p_sid, v_inv, coalesce(p->>'customer',''), coalesce(p->>'phone',''), coalesce(p->>'salesman',''),
            coalesce(p->>'date',''), coalesce((p->>'subtotal')::numeric,0), coalesce((p->>'discount')::numeric,0),
            coalesce((p->>'total')::numeric,0), coalesce(p->>'pay','Cash'), coalesce((p->>'ts')::bigint,0))
    returning id into v_id;
  for it in select * from jsonb_array_elements(p->'items') loop
    insert into hw_sale_items(shop_id,sale_id,part_id,part_name,qty,cost,price)
      values (p_sid, v_id, nullif(it->>'part_id','')::bigint, coalesce(it->>'part_name',''),
              coalesce((it->>'qty')::numeric,0), coalesce((it->>'cost')::numeric,0), coalesce((it->>'price')::numeric,0));
    if (it->>'part_id') is not null and (it->>'part_id') <> '' then
      update hw_parts set stock = stock - coalesce((it->>'qty')::numeric,0)
        where id = (it->>'part_id')::bigint and shop_id = p_sid;
    end if;
  end loop;
  return jsonb_build_object('ok',true,'id',v_id,'inv',v_inv);
end $fn$;

-- ---- Purchase: bump po, insert purchase + items, increment stock, supplier bal/incentive ----
create or replace function fn_hw_purchase(p_sid bigint, p jsonb)
returns jsonb language plpgsql as $fn$
declare v_no int; v_po text; v_id bigint; it jsonb; yr text := to_char(now(),'YYYY');
        v_amount numeric := coalesce((p->>'amount')::numeric,0);
        v_paid numeric := coalesce((p->>'paid')::numeric,0);
        v_inc numeric := coalesce((p->>'incentive_used')::numeric,0);
        v_supp bigint := nullif(p->>'supp_id','')::bigint;
begin
  update hw_shops set po_no = po_no + 1 where id = p_sid returning po_no into v_no;
  v_po := 'PO-'||yr||'-'||v_no;
  insert into hw_purchases(shop_id,po,supp_id,supp_name,inv_no,date,notes,amount,paid,incentive_used,status,ts)
    values (p_sid, v_po, v_supp, coalesce(p->>'supp_name',''), coalesce(p->>'inv_no',''), coalesce(p->>'date',''),
            coalesce(p->>'notes',''), v_amount, v_paid, v_inc, coalesce(p->>'status','received'), coalesce((p->>'ts')::bigint,0))
    returning id into v_id;
  for it in select * from jsonb_array_elements(p->'items') loop
    insert into hw_purchase_items(shop_id,pur_id,part_id,part_name,qty,price)
      values (p_sid, v_id, nullif(it->>'part_id','')::bigint, coalesce(it->>'part_name',''),
              coalesce((it->>'qty')::numeric,0), coalesce((it->>'price')::numeric,0));
    if (it->>'part_id') is not null and (it->>'part_id') <> '' then
      update hw_parts set stock = stock + coalesce((it->>'qty')::numeric,0),
                          cost  = case when coalesce((it->>'price')::numeric,0) > 0 then (it->>'price')::numeric else cost end
        where id = (it->>'part_id')::bigint and shop_id = p_sid;
    end if;
  end loop;
  if v_supp is not null then
    update hw_suppliers set bal = bal + (v_amount - v_paid - v_inc), incentive = incentive - v_inc
      where id = v_supp and shop_id = p_sid;
  end if;
  return jsonb_build_object('ok',true,'id',v_id,'po',v_po);
end $fn$;

-- ---- Service Job: create with parts (deduct stock) ----
create or replace function fn_hw_job_create(p_sid bigint, p jsonb)
returns jsonb language plpgsql as $fn$
declare v_no int; v_job text; v_id bigint; it jsonb;
begin
  update hw_shops set srv_no = srv_no + 1 where id = p_sid returning srv_no into v_no;
  v_job := 'SRV-'||v_no;
  insert into hw_jobs(shop_id,job,customer,phone,bike_no,bike_model,chassis,engine,mech_id,mech_name,salesman,status,
                      parts_total,parts_cost,discount,labour,total,pay,entry_ts,ts)
    values (p_sid, v_job, coalesce(p->>'customer',''), coalesce(p->>'phone',''), coalesce(p->>'bike_no',''),
            coalesce(p->>'bike_model',''), coalesce(p->>'chassis',''), coalesce(p->>'engine',''),
            nullif(p->>'mech_id','')::bigint, coalesce(p->>'mech_name',''), coalesce(p->>'salesman',''), 'open',
            coalesce((p->>'parts_total')::numeric,0), coalesce((p->>'parts_cost')::numeric,0),
            coalesce((p->>'discount')::numeric,0), coalesce((p->>'labour')::numeric,0),
            coalesce((p->>'total')::numeric,0), coalesce(p->>'pay',''), coalesce((p->>'entry_ts')::bigint,0), coalesce((p->>'ts')::bigint,0))
    returning id into v_id;
  for it in select * from jsonb_array_elements(coalesce(p->'parts','[]'::jsonb)) loop
    insert into hw_job_parts(shop_id,job_id,part_id,part_name,qty,cost,price)
      values (p_sid, v_id, nullif(it->>'part_id','')::bigint, coalesce(it->>'part_name',''),
              coalesce((it->>'qty')::numeric,0), coalesce((it->>'cost')::numeric,0), coalesce((it->>'price')::numeric,0));
    if (it->>'part_id') is not null and (it->>'part_id') <> '' then
      update hw_parts set stock = stock - coalesce((it->>'qty')::numeric,0) where id=(it->>'part_id')::bigint and shop_id=p_sid;
    end if;
  end loop;
  return jsonb_build_object('ok',true,'id',v_id,'job',v_job);
end $fn$;

-- ---- Service Job: replace parts list (restore old stock, deduct new) + update header ----
create or replace function fn_hw_job_update(p_sid bigint, p jsonb)
returns jsonb language plpgsql as $fn$
declare v_id bigint := (p->>'id')::bigint; it jsonb; old record;
begin
  -- restore stock from existing parts
  for old in select part_id, qty from hw_job_parts where job_id=v_id and shop_id=p_sid loop
    if old.part_id is not null then
      update hw_parts set stock = stock + old.qty where id=old.part_id and shop_id=p_sid;
    end if;
  end loop;
  delete from hw_job_parts where job_id=v_id and shop_id=p_sid;
  -- insert new parts + deduct
  for it in select * from jsonb_array_elements(coalesce(p->'parts','[]'::jsonb)) loop
    insert into hw_job_parts(shop_id,job_id,part_id,part_name,qty,cost,price)
      values (p_sid, v_id, nullif(it->>'part_id','')::bigint, coalesce(it->>'part_name',''),
              coalesce((it->>'qty')::numeric,0), coalesce((it->>'cost')::numeric,0), coalesce((it->>'price')::numeric,0));
    if (it->>'part_id') is not null and (it->>'part_id') <> '' then
      update hw_parts set stock = stock - coalesce((it->>'qty')::numeric,0) where id=(it->>'part_id')::bigint and shop_id=p_sid;
    end if;
  end loop;
  update hw_jobs set
    customer=coalesce(p->>'customer',customer), phone=coalesce(p->>'phone',phone),
    bike_no=coalesce(p->>'bike_no',bike_no), bike_model=coalesce(p->>'bike_model',bike_model),
    chassis=coalesce(p->>'chassis',chassis), engine=coalesce(p->>'engine',engine),
    mech_id=nullif(p->>'mech_id','')::bigint, mech_name=coalesce(p->>'mech_name',mech_name),
    salesman=coalesce(p->>'salesman',salesman), status=coalesce(p->>'status',status),
    parts_total=coalesce((p->>'parts_total')::numeric,parts_total), parts_cost=coalesce((p->>'parts_cost')::numeric,parts_cost),
    discount=coalesce((p->>'discount')::numeric,discount), labour=coalesce((p->>'labour')::numeric,labour),
    total=coalesce((p->>'total')::numeric,total), pay=coalesce(p->>'pay',pay),
    exit_ts=coalesce((p->>'exit_ts')::bigint,exit_ts)
    where id=v_id and shop_id=p_sid;
  return jsonb_build_object('ok',true,'id',v_id);
end $fn$;

-- ---- Service Job: delete (restore stock) ----
create or replace function fn_hw_job_delete(p_sid bigint, p jsonb)
returns jsonb language plpgsql as $fn$
declare v_id bigint := (p->>'id')::bigint; old record;
begin
  for old in select part_id, qty from hw_job_parts where job_id=v_id and shop_id=p_sid loop
    if old.part_id is not null then
      update hw_parts set stock = stock + old.qty where id=old.part_id and shop_id=p_sid;
    end if;
  end loop;
  delete from hw_jobs where id=v_id and shop_id=p_sid;   -- job_parts cascade
  return jsonb_build_object('ok',true);
end $fn$;

