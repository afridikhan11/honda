-- bootstrap: ek call mein shop ka poora data (app load par).
-- Bari tables newest-first + limit (naye client ke liye kaafi;
-- bohot bara data ho to aage server-side paging add ho sakti hai).
-- ============================================================
create or replace function fn_hw_bootstrap(p_sid bigint)
returns jsonb language sql as $fn$
select jsonb_build_object(
  'shopInfo', (select jsonb_build_object('name',name,'tagline',tagline,'phone',phone,'address',address) from hw_shops where id = p_sid),
  'counters', (select jsonb_build_object('inv',inv_no,'po',po_no,'srv',srv_no) from hw_shops where id = p_sid),
  'status',   (select status from hw_shops where id = p_sid),
  'users',    coalesce((select jsonb_agg(jsonb_build_object('id',id,'username',username,'name',name,'role',role) order by id) from hw_users where shop_id = p_sid),'[]'::jsonb),
  'parts',    coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.name) from (select * from hw_parts where shop_id=p_sid order by name limit 5000) x),'[]'::jsonb),
  'suppliers',coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.name) from (select * from hw_suppliers where shop_id=p_sid) x),'[]'::jsonb),
  'mechanics',coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.name) from (select * from hw_mechanics where shop_id=p_sid) x),'[]'::jsonb),
  'mechLedger',coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.id) from (select * from hw_mech_ledger where shop_id=p_sid order by id desc limit 3000) x),'[]'::jsonb),
  'employees',coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.code) from (select * from hw_employees where shop_id=p_sid) x),'[]'::jsonb),
  'empLedger',coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.id) from (select * from hw_emp_ledger where shop_id=p_sid order by id desc limit 3000) x),'[]'::jsonb),
  'expenses', coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.id desc) from (select * from hw_expenses where shop_id=p_sid order by id desc limit 3000) x),'[]'::jsonb),
  'kharadia', coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.id desc) from (select * from hw_kharadia where shop_id=p_sid order by id desc limit 3000) x),'[]'::jsonb),
  'purchases',coalesce((select jsonb_agg(jsonb_build_object(
                 'id',pu.id,'po',pu.po,'supp_id',pu.supp_id,'supp_name',pu.supp_name,'inv_no',pu.inv_no,'date',pu.date,'notes',pu.notes,
                 'amount',pu.amount,'paid',pu.paid,'incentive_used',pu.incentive_used,'status',pu.status,'ts',pu.ts,
                 'items', coalesce((select jsonb_agg(jsonb_build_object('id',i.id,'part_id',i.part_id,'part_name',i.part_name,'qty',i.qty,'price',i.price)) from hw_purchase_items i where i.pur_id=pu.id),'[]'::jsonb)
               ) order by pu.id desc) from (select * from hw_purchases where shop_id=p_sid order by id desc limit 1500) pu),'[]'::jsonb),
  'sales',    coalesce((select jsonb_agg(jsonb_build_object(
                 'id',s.id,'inv',s.inv,'customer',s.customer,'phone',s.phone,'salesman',s.salesman,'date',s.date,
                 'subtotal',s.subtotal,'discount',s.discount,'total',s.total,'pay',s.pay,'ts',s.ts,
                 'items', coalesce((select jsonb_agg(jsonb_build_object('id',i.id,'part_id',i.part_id,'part_name',i.part_name,'qty',i.qty,'cost',i.cost,'price',i.price)) from hw_sale_items i where i.sale_id=s.id),'[]'::jsonb)
               ) order by s.id desc) from (select * from hw_sales where shop_id=p_sid order by id desc limit 1500) s),'[]'::jsonb),
  'jobs',     coalesce((select jsonb_agg(jsonb_build_object(
                 'id',j.id,'job',j.job,'customer',j.customer,'phone',j.phone,'bike_no',j.bike_no,'bike_model',j.bike_model,'chassis',j.chassis,'engine',j.engine,
                 'mech_id',j.mech_id,'mech_name',j.mech_name,'salesman',j.salesman,'status',j.status,'parts_total',j.parts_total,'parts_cost',j.parts_cost,
                 'discount',j.discount,'labour',j.labour,'total',j.total,'pay',j.pay,'entry_ts',j.entry_ts,'exit_ts',j.exit_ts,'ts',j.ts,
                 'parts', coalesce((select jsonb_agg(jsonb_build_object('id',i.id,'part_id',i.part_id,'part_name',i.part_name,'qty',i.qty,'cost',i.cost,'price',i.price)) from hw_job_parts i where i.job_id=j.id),'[]'::jsonb)
               ) order by j.id desc) from (select * from hw_jobs where shop_id=p_sid order by id desc limit 1500) j),'[]'::jsonb),
  'warranty', coalesce((select jsonb_agg(to_jsonb(x)-'shop_id' order by x.id desc) from (select * from hw_warranty where shop_id=p_sid order by id desc limit 2000) x),'[]'::jsonb)
);
$fn$;

