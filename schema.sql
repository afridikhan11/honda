-- ---------- core: shop + logins ----------
create table if not exists hw_shops (
  id          bigint generated by default as identity primary key,
  name        text not null,
  tagline     text default '',
  phone       text default '',
  address     text default '',
  inv_no      integer default 4000,          -- Parts Sale invoice counter (INV-2026-xxxx)
  po_no       integer default 1000,          -- Purchase order counter (PO-2026-xxxx)
  srv_no      integer default 3000,          -- Service job counter (SRV-xxxx)
  status      text default 'active' check (status in ('trial','active','blocked')),
  trial_ends  date,
  created_at  timestamptz default now()
);
