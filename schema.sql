-- ---- Purchase: delete (reverse stock + supplier bal) ----
create or replace function fn_hw_purchase_delete(p_sid bigint, p jsonb)
returns jsonb language plpgsql as $fn$
declare v_id bigint := (p->>'id')::bigint; old record; h record;
begin
  select * into h from hw_purchases where id=v_id and shop_id=p_sid;
  if not found then return jsonb_build_object('ok',true); end if;
  for old in select part_id, qty from hw_purchase_items where pur_id=v_id and shop_id=p_sid loop
    if old.part_id is not null then
      update hw_parts set stock = greatest(0, stock - old.qty) where id=old.part_id and shop_id=p_sid;
    end if;
  end loop;
  if h.supp_id is not null then
    update hw_suppliers set bal = bal - (h.amount - h.paid - h.incentive_used), incentive = incentive + h.incentive_used
      where id=h.supp_id and shop_id=p_sid;
  end if;
  delete from hw_purchases where id=v_id and shop_id=p_sid;
  return jsonb_build_object('ok',true);
end $fn$;

